const fs = require('fs');
const path = require('path');

const contentDir = 'content';
const blogDir = path.join(contentDir, 'blog');
const projectDir = path.join(contentDir, 'projects');
const outputDir = 'lib/data';
const generatedBlogDir = path.join('lib', 'generated', 'blog');
const generatedProjectDir = path.join('lib', 'generated', 'projects');

fs.mkdirSync(outputDir, { recursive: true });

function parseFrontmatter(raw) {
  const match = raw.match(/^---\r?\n([\s\S]*?)\r?\n---\r?\n/);
  if (!match) return null;
  const result = {};
  const lines = match[1].split('\n');
  let currentKey = '';
  let inArray = false;

  for (const line of lines) {
    if (inArray) {
      if (line.trim().startsWith('- ')) {
        let item = line.trim().slice(2);
        if ((item.startsWith('"') && item.endsWith('"')) || (item.startsWith("'") && item.endsWith("'"))) {
          item = item.slice(1, -1);
        }
        if (!Array.isArray(result[currentKey])) result[currentKey] = [];
        result[currentKey].push(item);
      } else {
        inArray = false;
      }
      continue;
    }

    const idx = line.indexOf(':');
    if (idx === -1) continue;
    const key = line.slice(0, idx).trim();
    let value = line.slice(idx + 1).trim();
    currentKey = key;

    if (value.startsWith('[')) {
      if (value.endsWith(']')) {
        const arrayContent = value.slice(1, -1);
        result[key] = arrayContent.split(',').map(s => {
          s = s.trim();
          if ((s.startsWith('"') && s.endsWith('"')) || (s.startsWith("'") && s.endsWith("'"))) {
            s = s.slice(1, -1);
          }
          return s;
        }).filter(Boolean);
      } else {
        inArray = true;
        result[key] = [];
      }
    } else {
      let val = value.trim();
      if ((val.startsWith('"') && val.endsWith('"')) || (val.startsWith("'") && val.endsWith("'"))) {
        val = val.slice(1, -1);
      }
      result[key] = val;
    }
  }
  return result;
}

function stripFrontmatter(raw) {
  return raw.replace(/^---\r?\n[\s\S]*?\r?\n---\r?\n/, '').replace(/^\r?\n+/, '');
}

function localImagePath(collection, slug) {
  const directory = collection === 'blog' ? 'blogs' : 'projects';
  return `/images/${directory}/${slug}.png`;
}

function processCollection(dir, generatedDir) {
  if (!fs.existsSync(dir)) return [];
  fs.rmSync(generatedDir, { recursive: true, force: true });
  fs.mkdirSync(generatedDir, { recursive: true });
  return fs.readdirSync(dir)
    .filter(f => f.endsWith('.mdx'))
    .map(f => {
      const file = f.replace('.mdx', '');
      const raw = fs.readFileSync(path.join(dir, f), 'utf-8');
      const fm = parseFrontmatter(raw);
      const slug = (fm && fm.slug) || file;
      // 写入剥离 frontmatter 的干净正文，供 MDX 编译器渲染（编译器默认不剥离 frontmatter）
      fs.writeFileSync(path.join(generatedDir, `${slug}.mdx`), stripFrontmatter(raw));
      return {
        file,
        ...fm,
        slug,
        image: fm && fm.image ? localImagePath(path.basename(generatedDir), slug) : fm?.image,
      };
    });
}

function generateMdxRegistry(blogs, projects) {
  const lines = [
    "// Auto-generated by scripts/generate-content-data.js. Do not edit manually.",
    "import type { ComponentType } from 'react'",
    '',
  ];

  blogs.forEach((b, i) => {
    lines.push(`import Blog${i} from '@/lib/generated/blog/${b.slug}.mdx'`);
  });
  projects.forEach((p, i) => {
    lines.push(`import Project${i} from '@/lib/generated/projects/${p.slug}.mdx'`);
  });

  lines.push('');
  lines.push('export const blogComponents: Record<string, ComponentType<any>> = {');
  blogs.forEach((b, i) => lines.push(`  '${b.slug}': Blog${i},`));
  lines.push('};');
  lines.push('');
  lines.push('export const projectComponents: Record<string, ComponentType<any>> = {');
  projects.forEach((p, i) => lines.push(`  '${p.slug}': Project${i},`));
  lines.push('};');
  lines.push('');

  fs.writeFileSync(path.join('lib', 'mdx-registry.ts'), lines.join('\n'));
}

const blogs = processCollection(blogDir, generatedBlogDir);
const projects = processCollection(projectDir, generatedProjectDir);

const data = {
  blogs: blogs.map(({ file, ...rest }) => rest),
  projects: projects.map(({ file, ...rest }) => rest),
};
fs.writeFileSync(path.join(outputDir, 'content-data.json'), JSON.stringify(data, null, 2));

generateMdxRegistry(blogs, projects);

console.log('Generated:', blogs.length, 'blogs,', projects.length, 'projects');
